// Generate mods/live/wide/fixtures/pages-steps.testkit.ts from CODEFORGE_REPO/doc/design/tri/console/out-wide-all.
// Usage: CODEFORGE_REPO=/path/to/codeforge node mods/live/wide/fixtures/gen-pages.testkit.js
import fs from 'node:fs'
import path from 'node:path'

const repo = process.env.CODEFORGE_REPO
if (!repo) throw new Error('CODEFORGE_REPO env var is required')

const designDir = path.join(repo, 'doc', 'design', 'tri', 'console', 'out-wide-all')
const flow = JSON.parse(fs.readFileSync(path.join(designDir, 'flow.json'), 'utf8'))

// Minimal East Asian Width / zero-width check matching mods/tux/width.ts
const charWidth = (ch) => {
  const cp = ch.codePointAt(0)
  if (cp === undefined) return 0
  if (cp === 0 || (cp >= 0x0300 && cp <= 0x036f) || (cp >= 0xfe00 && cp <= 0xfe0f) || cp === 0x200d) return 0
  if (
    (cp >= 0x1100 && cp <= 0x115f) ||
    (cp >= 0x2e80 && cp <= 0x303e) ||
    (cp >= 0x3041 && cp <= 0x33bf) ||
    (cp >= 0x3400 && cp <= 0x4dbf) ||
    (cp >= 0x4e00 && cp <= 0xa4cf) ||
    (cp >= 0xac00 && cp <= 0xd7af) ||
    (cp >= 0xf900 && cp <= 0xfaff) ||
    (cp >= 0xfe10 && cp <= 0xfe6f) ||
    (cp >= 0xff01 && cp <= 0xff60) ||
    (cp >= 0xffe0 && cp <= 0xffe6) ||
    (cp >= 0x1f300 && cp <= 0x1faff) ||
    (cp >= 0x20000 && cp <= 0x3ffff)
  ) return 2
  return 1
}

const cols = (s, from, to) => {
  let out = ''
  let at = 0
  for (const ch of s) {
    const w = charWidth(ch)
    if (at >= from && at + w <= to) out += ch
    at += w
  }
  return out
}

const steps = flow
  .filter((entry) => entry.tab !== '待決')
  .map((entry) => {
    const screenPath = path.join(designDir, `209x49-s${entry.step}`, 'screen.txt')
    const lines = fs.readFileSync(screenPath, 'utf8').split(/\r?\n/)
    const band = lines.slice(25, 42).map((line) => cols(line, 0, 115))
    const pane = lines.slice(0, 42).map((line) => cols(line, 115, 209))
    return {
      id: entry.id,
      step: entry.step,
      tab: entry.tab,
      state: entry.state,
      title: entry.title,
      band,
      pane,
    }
  })

const outPath = path.join(path.dirname(new URL(import.meta.url).pathname), 'pages-steps.testkit.ts')
const header = [
  '// Generated by gen-pages.testkit.js from out-wide-all/209x49-s<N>/screen.txt (read-only design source).',
  '// Band: rows 25-41, cols 0-114 (17x115). Pane: rows 0-41, cols 115-208 (42x94).',
  'export type PageStep = { id: string; step: number; tab: string; state: string; title: string; band: string[]; pane: string[] }',
  'export const PAGE_STEPS: PageStep[] = ' + JSON.stringify(steps, null, 2) + '\n',
].join('\n')

fs.writeFileSync(outPath, header, 'utf8')
console.log(`Wrote ${steps.length} steps to ${outPath}`)
