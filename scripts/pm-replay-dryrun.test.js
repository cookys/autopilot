'use strict';
const assert = require('node:assert/strict');
const { makeManifest } = require('./pm-replay-dryrun.js');
const { SCREENING_QUOTA } = require('./pm-replay-slice.js');
const a = makeManifest(20261125), b = makeManifest(20261125), c = makeManifest(20261126);
assert.equal(JSON.stringify(a), JSON.stringify(b));
assert.notEqual(JSON.stringify(a), JSON.stringify(c));
assert.equal(a.events.length, 12);
for (const [type, n] of Object.entries(SCREENING_QUOTA)) assert.equal(a.events.filter(e => e.type === type).length, n);
console.log('PASS manifest determinism and quotas');
const { replay, dryRun } = require('./pm-replay-dryrun.js');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const crypto = require('node:crypto');
(async () => {
  const consistent = await replay(a);
  assert.equal(consistent.scored.S2.agreement, 1);
  assert.deepEqual(consistent.execution.results.slice(0, 4).map(r => r.arm), ['baseline', 'S2', 'S2', 'baseline']);
  assert.equal(consistent.execution.executedCount, 24);
  const divergent = await replay(a, { divergences: 3 });
  assert.equal(divergent.scored.S2.agreement, 9 / 12);
  assert.equal(divergent.comparison.treatment_paired, 1);
  assert.notEqual(divergent.scored.S2.agreement, divergent.comparison.treatment_paired);
  const mismatch = await replay(a, { mismatches: 3 });
  assert.equal(mismatch.scored.S2.agreement, 9 / 12);
  assert.equal(mismatch.comparison.treatment_paired, 9 / 12);
  console.log('PASS replay agreement and paired denominator');
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'pm-dryrun-test-'));
  const first = await dryRun(path.join(root, 'first'));
  await dryRun(path.join(root, 'second'));
  await dryRun(path.join(root, 'third'), 20261126);
  const read = name => fs.readFileSync(path.join(root, name, 'manifest.json'));
  assert.deepEqual(read('first'), read('second'));
  assert.notDeepEqual(read('first'), read('third'));
  const sha = data => crypto.createHash('sha256').update(data).digest('hex');
  console.log(`same-seed manifest sha256: ${sha(read('first'))} ${sha(read('second'))}`);
  assert.equal(first.report.manifest_sha256, sha(read('first')));
  assert.equal(first.report.non_dry_run.rejected, true);
  assert.match(first.report.non_dry_run.reason, /empty_whitelist/);
  assert.ok(['eliminate', 'inconclusive'].includes(first.report.verdict));
  assert.equal(first.report.negative_controls.probes.length, 7);
  if (first.report.negative_controls.skipped) console.log(`SKIP negative controls: ${first.report.negative_controls.reason}`);
  else assert.ok(first.report.negative_controls.probes.every(p => p.blocked));
  console.log('PASS report, empty pool rejection, and probe status');
  const { spawnSync } = require('node:child_process');
  const cliDir = path.join(root, 'cli');
  const cli = spawnSync(process.execPath, [path.join(__dirname, 'pm-replay-dryrun.js'), '--out', cliDir], { encoding: 'utf8', env: { PATH: process.env.PATH, HOME: root, TMPDIR: root } });
  assert.equal(cli.status, 0, cli.stderr);
  assert.equal(cli.stdout.trim().split('\n').at(-1), sha(fs.readFileSync(path.join(cliDir, 'report.json'))));
  console.log('PASS CLI report hash');
  // positive control: injected disagreement must show up in the report, per event, and move the verdict
  const clean = await dryRun(path.join(root, 'pc-clean'), 20261125, {});
  const injected = await dryRun(path.join(root, 'pc-inj'), 20261125, { mismatches: 3 });
  const wrong = rows => rows.filter(r => !r.S2.correct).length;
  assert.equal(wrong(clean.report.per_event), 0, 'clean run has no wrong S2 events');
  assert.equal(wrong(injected.report.per_event), 3, 'exactly the 3 injected events are wrong');
  assert.equal(injected.report.per_event.filter(r => !r.baseline.correct).length, 0, 'baseline arm untouched');
  assert.ok(injected.report.arms.S2.full < clean.report.arms.S2.full, 'S2 agreement must fall');
  assert.notEqual(injected.report.verdict, 'inconclusive', 'verdict must move once 3/12 diverge');
  const div = await dryRun(path.join(root, 'pc-div'), 20261125, { divergences: 3 });
  assert.equal(div.report.per_event.filter(r => r.S2.divergent).length, 3, 'exactly 3 divergent S2 events');
  console.log('PASS positive control (3/12 injected, per-event report)');
  console.log('PASS 6 test cases');
})().catch(e => { console.error(e); process.exitCode = 1; });
