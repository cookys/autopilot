#!/usr/bin/env node
'use strict';
// cost-table.js -- cells and estimated cost per arm / role / model for a prereg design. No model call.
//   cost-table.js --row pilot|formal [--md | --json]
// Reads prereg/<row>.json (design block) and cost-model.json. Used by prereg/build-prereg.js and checked by a test
// so that the numbers in the prereg, COST-TABLE.md and this script cannot drift apart.
const fs = require('fs');
const path = require('path');

const root = __dirname;
const readJson = (f) => JSON.parse(fs.readFileSync(path.join(root, f), 'utf8'));

function rateFor(seatKind, model) {
  const r = model.rates_usd_per_cell;
  if (seatKind === 'weak1') return { low: r.haiku.usd, high: r.haiku.usd };
  if (seatKind === 'weak2') return { low: r.kimi.usd, high: r.kimi.usd };
  if (seatKind === 'strong') return { low: r.sonnet_low.usd, high: r.sonnet_high.usd };
  throw new Error(`unknown seat ${seatKind}`);
}

function compute(design, model = readJson('cost-model.json')) {
  const rows = [];
  for (const arm of design.arms) {
    for (const seat of arm.seats) {
      const reps = design.reps[arm.id][seat];
      for (const role of design.roles) {
        const cells = design.tasks_by_role[role] * reps;
        const rate = rateFor(seat, model);
        rows.push({ arm: arm.id, role, seat, reps, cells, usd_low: +(cells * rate.low).toFixed(4), usd_high: +(cells * rate.high).toFixed(4) });
      }
    }
  }
  const sum = (f) => +rows.reduce((n, r) => n + f(r), 0).toFixed(4);
  const bySeat = {};
  for (const r of rows) { bySeat[r.seat] = bySeat[r.seat] || { cells: 0, usd_low: 0, usd_high: 0 }; bySeat[r.seat].cells += r.cells; bySeat[r.seat].usd_low = +(bySeat[r.seat].usd_low + r.usd_low).toFixed(4); bySeat[r.seat].usd_high = +(bySeat[r.seat].usd_high + r.usd_high).toFixed(4); }
  const total = { cells: sum((r) => r.cells), usd_low: sum((r) => r.usd_low), usd_high: sum((r) => r.usd_high) };
  return { rows, bySeat, total, with_margin_high: +(total.usd_high * model.estimate_margin).toFixed(2), margin: model.estimate_margin };
}

function markdown(row, c, cap) {
  const L = [];
  L.push(`# Cell cost table: ${row}`, '', `Generated by \`node cost-table.js --row ${row} --md\` from \`prereg/${row}.json\` and \`cost-model.json\`. Do not edit by hand.`, '');
  L.push('| arm | role | seat | cells | USD low | USD high |', '|---|---|---|---:|---:|---:|');
  for (const r of c.rows) L.push(`| ${r.arm} | ${r.role} | ${r.seat} | ${r.cells} | ${r.usd_low.toFixed(3)} | ${r.usd_high.toFixed(3)} |`);
  L.push('', '| seat | cells | USD low | USD high |', '|---|---:|---:|---:|');
  const label = { weak1: 'weak1 (Haiku 5.5, Claude quota)', weak2: 'weak2 (kimi-code 2.3.0, its own quota; unit price NOT measured, Haiku-rate placeholder)', strong: 'strong (Sonnet, Claude quota)' };
  for (const [s, v] of Object.entries(c.bySeat)) L.push(`| ${label[s] || s} | ${v.cells} | ${v.usd_low.toFixed(2)} | ${v.usd_high.toFixed(2)} |`);
  L.push(`| total | ${c.total.cells} | ${c.total.usd_low.toFixed(2)} | ${c.total.usd_high.toFixed(2)} |`, '');
  if (c.bySeat.weak2) L.push('', 'weak2 cells run on the kimi-code subscription, not on the Claude quota. No unit price has been measured for them; the row uses the Haiku rate as a placeholder so the cells still count against the estimate and the cap. weak2 results are reported apart and do not enter the verdict.');
  L.push(`Estimate with the ${c.margin}x margin on the high column: ${c.with_margin_high} USD. Cap for this row: ${cap} USD.`, '');
  return `${L.join('\n')}\n`;
}

if (require.main === module) {
  const argv = process.argv.slice(2);
  const i = argv.indexOf('--row');
  const row = i >= 0 ? argv[i + 1] : undefined;
  if (!row || !/^[a-z0-9-]+$/.test(row)) { console.error('usage: cost-table.js --row pilot|formal [--md|--json]'); process.exit(2); }
  const prereg = readJson(`prereg/${row}.json`);
  const c = compute(prereg.design);
  if (argv.includes('--json')) process.stdout.write(`${JSON.stringify(c, null, 2)}\n`);
  else process.stdout.write(markdown(row, c, prereg.cost.cap_usd));
}
module.exports = { compute, markdown, rateFor };
