#!/usr/bin/env node
'use strict';
/**
 * hook-harness-matrix.js — per-hook x per-harness support matrix with verification dates (BL-0026).
 *
 * "Registered" is DERIVED from the real wiring (hooks/hooks.json for Claude Code,
 * platforms/codex/hooks/hooks.json for Codex). "Verified" is NEVER derived: it comes only from
 * hooks/harness-support-evidence.json, rows a person added after a hook-probe run showed the
 * event actually fired. No evidence row => the cell says 未驗證. A hook being registered is not a
 * hook running (references/evidence-discipline.md). Each evidence row has a kind: only `fired`
 * (a probe run saw the event fire) is shown as 驗證 with a date; `packaged` (the shipped package
 * contains the hook) and `doc` (a doc claims it) show as 已打包／文件宣稱 (未驗證觸發), never as
 * verified. OpenCode and agy have no hooks.json wiring of ours: their cells stay — and an evidence
 * row for them is rejected (not a registered stem/event) until we wire them.
 *
 * Usage:
 *   node scripts/hook-harness-matrix.js            # print the matrix markdown
 *   node scripts/hook-harness-matrix.js --write    # regenerate docs/hook-harness-matrix.md
 *   node scripts/hook-harness-matrix.js --check    # exit 1 if the doc drifted or an evidence row is
 *                                                  # bogus; WARN (exit 0) on rows older than 60 days
 *   --repo <dir>   operate on another tree (tests)      --today <YYYY-MM-DD>  (tests)
 * Evidence row: {stem, harness: "claude"|"codex"|"opencode"|"agy", event, kind: "fired"|"packaged"|"doc", verified_at, evidence}.
 * Exit: 0 ok / 1 drift or bad evidence / 2 usage or unreadable input.
 */
const fs = require('fs');
const path = require('path');

const STALE_DAYS = 60;
const HARNESSES = [['claude', 'Claude Code'], ['codex', 'Codex'], ['opencode', 'OpenCode'], ['agy', 'agy']];
const UNVERIFIED = '未驗證';

function die(msg, code = 2) { console.error(msg); process.exit(code); }

function parseArgs(argv) {
  const o = { mode: 'print', repo: path.resolve(__dirname, '..'), today: new Date().toISOString().slice(0, 10) };
  for (let i = 0; i < argv.length; i += 1) {
    const a = argv[i];
    if (a === '--write') o.mode = 'write';
    else if (a === '--check') o.mode = 'check';
    else if (a === '--repo') o.repo = path.resolve(argv[++i] || die('--repo needs a dir'));
    else if (a === '--today') o.today = argv[++i] || die('--today needs a date');
    else die(`unknown argument: ${a}`);
  }
  return o;
}

function readJson(repo, rel) {
  try { return JSON.parse(fs.readFileSync(path.join(repo, rel), 'utf8')); }
  catch (e) { return die(`cannot read/parse ${rel}: ${e.message}`); }
}

// { stem -> Set(event) } from a hooks.json `hooks` block.
function registered(block) {
  const out = new Map();
  for (const [event, matchers] of Object.entries(block || {})) {
    for (const m of matchers) {
      for (const h of m.hooks || []) {
        const mm = /hooks\/([A-Za-z0-9_-]+)\.(js|sh)/u.exec(h.command || '');
        if (!mm) continue;
        if (!out.has(mm[1])) out.set(mm[1], new Set());
        out.get(mm[1]).add(event);
      }
    }
  }
  return out;
}

function load(repo) {
  const claude = registered(readJson(repo, 'hooks/hooks.json').hooks);
  const codex = registered(readJson(repo, 'platforms/codex/hooks/hooks.json').hooks);
  let evidence = [];
  const ep = path.join(repo, 'hooks/harness-support-evidence.json');
  if (fs.existsSync(ep)) evidence = readJson(repo, 'hooks/harness-support-evidence.json').rows || [];
  return { wiring: { claude, codex, opencode: new Map(), agy: new Map() }, evidence };
}

function cell(data, stem, harness) {
  const events = [...(data.wiring[harness].get(stem) || [])].sort();
  const rows = data.evidence.filter((r) => r.stem === stem && r.harness === harness);
  const reg = events.length ? events.join(', ') : '—';
  const ver = events.map((ev) => {
    const r = rows.find((x) => x.event === ev);
    if (!r) return null;
    if (r.kind === 'fired') return `驗證: ${ev} ${r.verified_at}`;
    return `${r.kind === 'packaged' ? '已打包' : '文件宣稱'}（未驗證觸發）: ${ev} ${r.verified_at}`;
  }).filter(Boolean);
  if (!events.length) return rows.length ? `— (${rows.length} orphan evidence row)` : '—';
  return `${reg}<br>${ver.length ? ver.join('; ') : UNVERIFIED}`;
}

function render(data) {
  const stems = new Set();
  for (const [h] of HARNESSES) for (const s of data.wiring[h].keys()) stems.add(s);
  const lines = [
    '# Hook x harness support matrix',
    '',
    '<!-- GENERATED by scripts/hook-harness-matrix.js --write. Do not edit by hand. -->',
    '',
    'Registered events are derived from the real wiring (`hooks/hooks.json`, `platforms/codex/hooks/hooks.json`).',
    `In \`hooks/harness-support-evidence.json\`, a \`fired\` row (a probe run saw the event fire) renders as 驗證 plus its date; a \`packaged\` or \`doc\` row renders as 已打包／文件宣稱（未驗證觸發） plus its recorded date, which is not a verification date; with no row the cell says ${UNVERIFIED} (not verified). OpenCode and agy have no hook wiring of ours: \`—\`. A registered hook is not a running hook.`,
    '',
    `| Hook | ${HARNESSES.map(([, n]) => n).join(' | ')} |`,
    `|---|${HARNESSES.map(() => '---').join('|')}|`,
  ];
  for (const stem of [...stems].sort()) {
    lines.push(`| \`${stem}\` | ${HARNESSES.map(([h]) => cell(data, stem, h)).join(' | ')} |`);
  }
  lines.push('', '`opt-in-multiplexer` hosts the opt-in PreToolUse / PostToolUse / Stop stems for Claude Code; their tiers are in `scripts/check-hook-inventory.js`.', '');
  return lines.join('\n');
}

function problems(data, today) {
  const errs = []; const warns = [];
  const todayMs = Date.parse(`${today}T00:00:00Z`);
  for (const r of data.evidence) {
    const tag = `evidence ${r.harness}/${r.stem}/${r.event}`;
    if (!HARNESSES.some(([h]) => h === r.harness)) { errs.push(`${tag}: unknown harness`); continue; }
    if (!(data.wiring[r.harness].get(r.stem) || new Set()).has(r.event)) {
      errs.push(`${tag}: not a registered (stem, event) on that harness — evidence for a hook that is not wired`);
    }
    if (!['fired', 'packaged', 'doc'].includes(r.kind)) errs.push(`${tag}: kind must be fired|packaged|doc`);
    if (typeof r.evidence !== 'string' || !r.evidence.trim()) errs.push(`${tag}: empty evidence pointer`);
    const t = /^\d{4}-\d{2}-\d{2}$/u.test(r.verified_at || '') ? Date.parse(`${r.verified_at}T00:00:00Z`) : NaN;
    if (Number.isNaN(t)) errs.push(`${tag}: verified_at is not YYYY-MM-DD`);
    else if (t > todayMs) errs.push(`${tag}: verified_at is in the future`);
    else if ((todayMs - t) / 86400000 > STALE_DAYS) warns.push(`${tag}: verified ${r.verified_at}, older than ${STALE_DAYS} days — re-probe`);
  }
  return { errs, warns };
}

function main() {
  const o = parseArgs(process.argv.slice(2));
  const data = load(o.repo);
  const md = render(data);
  const docPath = path.join(o.repo, 'docs/hook-harness-matrix.md');
  if (o.mode === 'print') { process.stdout.write(md); return; }
  if (o.mode === 'write') { fs.writeFileSync(docPath, md); console.log(`wrote ${path.relative(o.repo, docPath)}`); return; }
  const { errs, warns } = problems(data, o.today);
  let have = null;
  try { have = fs.readFileSync(docPath, 'utf8'); } catch { /* missing */ }
  if (have !== md) errs.push('docs/hook-harness-matrix.md is missing or differs from the wiring — run: node scripts/hook-harness-matrix.js --write');
  for (const w of warns) console.error(`WARN ${w}`);
  if (errs.length) { for (const e of errs) console.error(`FAIL ${e}`); process.exit(1); }
  console.log('hook-harness-matrix: ok');
}

main();
