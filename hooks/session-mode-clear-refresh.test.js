'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const home = fs.mkdtempSync(path.join(os.tmpdir(), 'clear-refresh-'));
process.env.HOME = home;
const dir = path.join(home, 'markers'); fs.mkdirSync(dir);
const env = { PATH: process.env.PATH, HOME: home, AUTOPILOT_SESSION_MODE_DIR: dir };
const file = path.join(dir, 'clear.json');
const invoke = (name, payload) => spawnSync(process.execPath, [path.join(__dirname, name)], { env, input: JSON.stringify(payload), encoding: 'utf8' });
test('clear clamps then first prompt refreshes the same level marker', () => {
  fs.writeFileSync(file, JSON.stringify({ session_id: 'clear', level: 'l5', stage: 'verify', root_run_id: 'root', expires_at: new Date(Date.now() + 86400000).toISOString() }));
  assert.equal(invoke('session-mode-end.js', { session_id: 'clear', reason: 'clear' }).status, 0);
  const clamped = JSON.parse(fs.readFileSync(file));
  assert.ok(Date.parse(clamped.expires_at) <= Date.now() + 1200000);
  const manifest = require('./hooks.json');
  assert.ok(manifest.hooks.UserPromptSubmit.some(e => e.hooks.some(h => h.command.includes('/session-mode-refresh.js'))));
  const profile = require('../profiles/hook-classes.json');
  assert.ok(JSON.stringify(profile).includes('"stem":"session-mode-refresh","class":"invariant_effect"'));
  const before = Date.now();
  assert.equal(invoke('session-mode-refresh.js', { session_id: 'clear' }).status, 0);
  const after = Date.now();
  const refreshed = JSON.parse(fs.readFileSync(file));
  assert.ok(Date.parse(refreshed.expires_at) >= before + 86400000 && Date.parse(refreshed.expires_at) <= after + 86400000);
  assert.deepEqual([refreshed.level, refreshed.stage, refreshed.root_run_id], ['l5', 'verify', 'root']);
  require('../scripts/session-mode').sweepExpiredMarkers(dir, null, after + 21 * 60000, { max: 0, graceMs: 0 });
  assert.equal(fs.existsSync(file), true);
});
