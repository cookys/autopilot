#!/usr/bin/env node
// mods/live/gen-band-contract.js — compile the shared band/statusline contract.
//
// A hooks module imports only code files (.ts .tsx .js …), never .json, and cannot import node builtins.
// band-statusline-contract.json is the only editable copy. This writes band-contract-data.ts, which
// band-contract.ts imports. Glyphs are \u escapes so the design lint does not see a raw drawing glyph
// outside ui.ts. The values equal the JSON.
//
//   node mods/live/gen-band-contract.js           write band-contract-data.ts
//   node mods/live/gen-band-contract.js --check   exit 1 when the compiled file drifts or the JSON is the wrong shape
//
// exit codes: 0 ok · 1 check failed · 2 usage / unreadable input

'use strict';
const fs = require('fs');
const path = require('path');

const dir = __dirname;
const jsonPath = path.join(dir, 'band-statusline-contract.json');
const outPath = path.join(dir, 'band-contract-data.ts');
const KEYS = ['quota_warn_pct', 'quota_error_pct', 'round', 'bar_on', 'bar_off', 'alert', 'age'];

function readContract() {
  let raw;
  try {
    raw = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
  } catch (e) {
    process.stderr.write(`gen-band-contract: cannot read band-statusline-contract.json: ${e.message}\n`);
    process.exit(2);
  }
  if (typeof raw !== 'object' || raw === null || Array.isArray(raw)) failRead('not an object');
  const keys = Object.keys(raw);
  if (keys.length !== KEYS.length || KEYS.some((k, i) => keys[i] !== k)) failRead('keys must be ' + KEYS.join(', ') + ' in that order');
  if (typeof raw.quota_warn_pct !== 'number' || typeof raw.quota_error_pct !== 'number') failRead('thresholds must be numbers');
  if (raw.round !== 'floor') failRead('round must be floor');
  for (const k of ['bar_on', 'bar_off', 'alert', 'age']) {
    if (typeof raw[k] !== 'string' || raw[k].length === 0) failRead(k + ' must be a non-empty string');
    for (const ch of raw[k]) if (ch.codePointAt(0) > 0xffff) failRead(k + ' must stay in the BMP');
  }
  return raw;
}

function failRead(why) {
  process.stderr.write(`gen-band-contract: ${why}\n`);
  process.exit(2);
}

// Source text only. A codepoint outside ASCII is a \u escape, so the compiled file draws nothing by itself.
function jsString(s) {
  let out = '"';
  for (const ch of s) {
    const cp = ch.codePointAt(0);
    if (ch === '"' || ch === '\\') out += '\\' + ch;
    else if (cp < 0x20 || cp > 0x7e) out += '\\u' + cp.toString(16).padStart(4, '0');
    else out += ch;
  }
  return out + '"';
}

function lit(v) {
  if (typeof v === 'number') return String(v);
  return jsString(v);
}

function render(raw) {
  const lines = KEYS.map((k) => `  ${k}: ${lit(raw[k])},`);
  return '// GENERATED by mods/live/gen-band-contract.js from band-statusline-contract.json. Do not edit: change the JSON, then run\n'
    + '//   node mods/live/gen-band-contract.js\n'
    + '// A hooks module imports only code files, never .json. Glyphs are \\u escapes; the values equal the JSON.\n\n'
    + 'export const BAND_CONTRACT_RAW = {\n'
    + lines.join('\n') + '\n'
    + '}\n';
}

function main(argv) {
  const raw = readContract();
  const generated = render(raw);
  if (argv.includes('--check')) {
    let onDisk = null;
    try { onDisk = fs.readFileSync(outPath, 'utf8'); } catch (_e) { /* none */ }
    if (onDisk !== generated) {
      process.stderr.write('FAIL band-contract-data.ts is out of date: run `node mods/live/gen-band-contract.js`\n');
      return 1;
    }
    process.stdout.write('gen-band-contract: ok\n');
    return 0;
  }
  if (argv.length > 0) {
    process.stderr.write('usage: node mods/live/gen-band-contract.js [--check]\n');
    return 2;
  }
  fs.writeFileSync(outPath, generated);
  process.stdout.write('gen-band-contract: wrote band-contract-data.ts\n');
  return 0;
}

if (require.main === module) process.exit(main(process.argv.slice(2)));
module.exports = { render, readContract };
