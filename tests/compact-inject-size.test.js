'use strict';
const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');
const Module = require('module');
const { buildResumeBlock, readMarker, digestResume } = require('../hooks/lib/pm-resume');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'compact-size-'));
const env = { ...process.env, HOME: tmp, TMPDIR: tmp, XDG_RUNTIME_DIR: tmp, FLEET_ADDRESS: 'test/pm--claude', AUTOPILOT_PRICES_FETCH: '0', AUTOPILOT_UPDATE_CHECK: '0', CLAUDE_PLUGIN_ROOT: path.resolve(__dirname, '..') };
const ids = Array.from({ length: 25 }, (_, i) => `01M88BSXPGS4HG0KRN79VX${String(i).padStart(4, '0')}`);
const resume = ['RESUME pm--claude 角色 pm', 'IN_FLIGHT', ...ids.slice(0, 5).map((id, i) => `${id} task ${i} ${'x'.repeat(200)}`), 'UNANSWERED', ...ids.slice(5).map(id => `${id} message`), 'UNLANDED', 'z'.repeat(8800)].join('\n');
const runner = () => ({ status: 0, stdout: resume });
const original = buildResumeBlock({ source: 'startup', session_id: 's' }, { env, runner });
const oldSource = spawnSync('git', ['show', '5448c54602d6776a6b569ec912aaef7503460342:hooks/lib/pm-resume.js'], { encoding: 'utf8' });
assert.strictEqual(oldSource.status, 0);
const oldModule = new Module(require.resolve('../hooks/lib/pm-resume'));
oldModule.filename = require.resolve('../hooks/lib/pm-resume');
oldModule.paths = module.paths;
oldModule._compile(oldSource.stdout, oldModule.filename);
assert.strictEqual(original, oldModule.exports.buildResumeBlock({ source: 'startup', session_id: 's' }, { env, runner }));
const fleet = path.join(tmp, 'fleet');
fs.writeFileSync(fleet, `#!/bin/sh\ncat '${path.join(tmp, 'resume')}'\n`, { mode: 0o755 });
fs.writeFileSync(path.join(tmp, 'resume'), resume);
env.FLEET_BIN = fleet;
fs.mkdirSync(path.join(tmp, '.autopilot'), { recursive: true });
fs.writeFileSync(path.join(tmp, '.autopilot', 'compaction-state-s.md'), `## 未回 fleet 訊息 (reserved, never cut)\nKEEP_UNANSWERED\n## Open fleet tasks (reserved, never cut)\nKEEP_TASKS\n## Transcript Tail\n${'t'.repeat(6800)}`);
const oldHook = spawnSync('git', ['show', '5448c54602d6776a6b569ec912aaef7503460342:hooks/session-start.js'], { encoding: 'utf8' });
assert.strictEqual(oldHook.status, 0);
const oldHookPath = path.join(tmp, 'old-hook.js');
fs.writeFileSync(oldHookPath, oldHook.stdout);
const oldResumePath = path.join(tmp, 'old-resume.js');
fs.writeFileSync(oldResumePath, oldSource.stdout);
const payload = JSON.stringify({ source: 'compact', session_id: 's', cwd: tmp });
const oldArgs = ['-e', `const Module = require('module'); const fs = require('fs'); const old = new Module(${JSON.stringify(require.resolve('../hooks/lib/pm-resume'))}); old.filename = ${JSON.stringify(require.resolve('../hooks/lib/pm-resume'))}; old.paths = module.paths; old._compile(fs.readFileSync(${JSON.stringify(oldResumePath)}, 'utf8'), old.filename); require.cache[old.filename] = old; const m = new Module(${JSON.stringify(path.resolve(__dirname, '../hooks/session-start.js'))}); m.filename = ${JSON.stringify(path.resolve(__dirname, '../hooks/session-start.js'))}; m.paths = module.paths; m._compile(fs.readFileSync(${JSON.stringify(oldHookPath)}, 'utf8'), m.filename);`];
const oldRun = spawnSync(process.execPath, oldArgs, { env, input: payload, encoding: 'utf8' });
assert.strictEqual(oldRun.status, 0, oldRun.stderr);
const before = JSON.parse(oldRun.stdout).hookSpecificOutput.additionalContext;
const startupPayload = JSON.stringify({ source: 'startup', session_id: 'startup', cwd: tmp });
const oldStartup = spawnSync(process.execPath, oldArgs, { env, input: startupPayload, encoding: 'utf8' });
const newStartup = spawnSync(process.execPath, [path.resolve(__dirname, '../hooks/session-start.js')], { env, input: startupPayload, encoding: 'utf8' });
assert.strictEqual(oldStartup.status, 0, oldStartup.stderr);
assert.strictEqual(newStartup.status, 0, newStartup.stderr);
assert.strictEqual(newStartup.stdout, oldStartup.stdout, 'startup output must match baseline byte for byte');
const noFlight = digestResume('OVERFLOW 超出上限\nRESUME seat 角色 pm\nUNLANDED tasks\nlong detail', { maxChars: 3000 });
assert.ok(noFlight.includes('UNLANDED') && noFlight.includes('--all'));
assert.ok(!noFlight.includes('long detail'));
fs.writeFileSync(path.join(tmp, '.autopilot', 'compaction-state-s.md'), `## 未回 fleet 訊息 (reserved, never cut)\nKEEP_UNANSWERED\n## Open fleet tasks (reserved, never cut)\nKEEP_TASKS\n## Transcript Tail\n${'t'.repeat(6800)}`);
const run = spawnSync(process.execPath, [path.resolve(__dirname, '../hooks/session-start.js')], { env, input: JSON.stringify({ source: 'compact', session_id: 's', cwd: tmp }), encoding: 'utf8' });
assert.strictEqual(run.status, 0, run.stderr);
const context = JSON.parse(run.stdout).hookSpecificOutput.additionalContext;
console.log(`前 ${before.length} 字元 / 後 ${context.length} 字元`);
assert.ok(context.length <= 8000, `compact context ${context.length} > 8000`);
for (const id of ids) assert.ok(context.includes(id), `missing ${id}`);
assert.ok(context.includes('KEEP_UNANSWERED') && context.includes('KEEP_TASKS'));
assert.ok(context.includes('fleet pm resume --seat pm--claude --role pm --all'));
assert.deepStrictEqual(readMarker('s', env).ids, ids);
console.log('compact injection passed');
