#!/usr/bin/env node
// mods/live/gen-locales.js — compile the live mod's string tables.
//
// A hooks module can import only code files, never .json, so the editable sources `locales/en.json` (source of truth, complete) and
// `locales/zh-TW.json` are compiled into `locales.ts` (exports EN, ZH_TW). Built-ins only (Node >= 20.10).
//
//   node mods/live/gen-locales.js           write locales.ts
//   node mods/live/gen-locales.js --check   exit 1 on: locales.ts drift from the JSON · an id missing from either file · a placeholder set that differs
//                                           between the two files · a `t('id')` literal in the code that en lacks · an en id nothing uses ·
//                                           a key-column label (label.*) wider than 12 display cells in either locale ·
//                                           a kv()/rule() label passed as a literal instead of t()
//
// exit codes: 0 ok · 1 check failed · 2 usage / unreadable input

'use strict';
const fs = require('fs');
const path = require('path');

const dir = __dirname;
const SOURCES = ['model.ts', 'tabs.ts', 'ui.ts', 'pane.tsx', 'band.tsx', 'register.ts', 'i18n.ts'];
// ids the code builds from a prefix (`t('tab.' + id)`, `'stage.' + node`, ...): an en id under one of these is considered used
const DYNAMIC_PREFIXES = ['ui.state.', 'tab.', 'stage.', 'legend.', 'residue.why.', 'verdict.', 'spend.mode_', 'reason.permission', 'reason.question'];
const KEY_COLUMN_CELLS = 12;

function readJson(file) {
  try {
    const v = JSON.parse(fs.readFileSync(path.join(dir, 'locales', file), 'utf8'));
    if (typeof v !== 'object' || v === null || Array.isArray(v)) throw new Error('not an object');
    for (const [k, x] of Object.entries(v)) if (typeof x !== 'string') throw new Error(`value of ${k} is not a string`);
    return v;
  } catch (e) {
    process.stderr.write(`gen-locales: cannot read locales/${file}: ${e.message}\n`);
    process.exit(2);
  }
}

function render(en, zh) {
  const table = (name, obj) => `export const ${name}: Record<string, string> = ${JSON.stringify(obj, null, 2)}\n`;
  return '// GENERATED by mods/live/gen-locales.js from locales/en.json and locales/zh-TW.json. Do not edit: change the JSON, then run\n'
    + '//   node mods/live/gen-locales.js\n'
    + '// (a hooks module can import only code files, never .json).\n\n'
    + table('EN', en) + '\n' + table('ZH_TW', zh);
}

const cellWidth = (c) => {
  if (c === 0 || (c >= 0x0300 && c <= 0x036f) || (c >= 0x200b && c <= 0x200f) || (c >= 0xfe00 && c <= 0xfe0f)) return 0;
  return (c >= 0x1100 && c <= 0x115f) || (c >= 0x2e80 && c <= 0x303e) || (c >= 0x3041 && c <= 0x33ff) || (c >= 0x3400 && c <= 0x4dbf)
    || (c >= 0x4e00 && c <= 0x9fff) || (c >= 0xac00 && c <= 0xd7a3) || (c >= 0xf900 && c <= 0xfaff) || (c >= 0xfe30 && c <= 0xfe4f)
    || (c >= 0xff00 && c <= 0xff60) || (c >= 0xffe0 && c <= 0xffe6) ? 2 : 1;
};
const displayWidth = (s) => { let w = 0; for (const ch of s) w += cellWidth(ch.codePointAt(0)); return w; };
const placeholders = (s) => [...new Set([...s.matchAll(/\{(\w+)\}/g)].map((m) => m[1]))].sort().join(',');
const baseId = (id) => id.replace(/\.(one|other)$/, '');

function check(en, zh, srcDir = dir) {
  const problems = [];
  const enIds = Object.keys(en);
  const zhIds = new Set(Object.keys(zh));
  for (const id of enIds) if (!zhIds.has(id)) problems.push(`zh-TW lacks ${id}`);
  for (const id of zhIds) if (en[id] === undefined) problems.push(`en lacks ${id} (en is the source of truth)`);
  for (const id of enIds) if (zh[id] !== undefined && placeholders(en[id]) !== placeholders(zh[id])) problems.push(`placeholders differ for ${id}: en {${placeholders(en[id])}} vs zh-TW {${placeholders(zh[id])}}`);
  for (const id of enIds) if (id.startsWith('label.')) for (const [name, table] of [['en', en], ['zh-TW', zh]]) {
    if (table[id] !== undefined && displayWidth(table[id]) > KEY_COLUMN_CELLS) problems.push(`${name} ${id} is ${displayWidth(table[id])} cells (key column is ${KEY_COLUMN_CELLS})`);
  }
  let code = '';
  for (const f of SOURCES) { try { code += fs.readFileSync(path.join(srcDir, f), 'utf8') + '\n'; } catch (_e) { problems.push(`cannot read ${f}`); } }
  const exists = (id) => en[id] !== undefined || en[id + '.one'] !== undefined || en[id + '.other'] !== undefined;
  for (const m of code.matchAll(/\bt\(\s*'([\w.-]+)'\s*[,)]/g)) if (!exists(m[1])) problems.push(`code uses t('${m[1]}') but en has no such id`);
  for (const id of new Set(enIds.map(baseId))) {
    if (DYNAMIC_PREFIXES.some((p) => id.startsWith(p))) continue;
    if (!code.includes(`'${id}'`)) problems.push(`en id ${id} is not used by the code`);
  }
  // a key-column label or a rule title passed as a string literal is an untranslated word: kv('x', ...) / rule('x', ...) must go through t()
  for (const m of code.matchAll(/\b(kv|rule)\(\s*(['"`])((?:(?!\2).)+)\2/g)) problems.push(`${m[1]}(${m[2]}${m[3]}${m[2]}, ...) passes a literal label; use t('label.…') / t('…')`);
  const generated = render(en, zh);
  let onDisk = null;
  try { onDisk = fs.readFileSync(path.join(dir, 'locales.ts'), 'utf8'); } catch (_e) { /* none */ }
  if (onDisk !== generated) problems.push('locales.ts is out of date: run `node mods/live/gen-locales.js`');
  return problems;
}

function main(argv) {
  const en = readJson('en.json');
  const zh = readJson('zh-TW.json');
  if (argv.includes('--check')) {
    const problems = check(en, zh);
    if (problems.length > 0) {
      process.stderr.write(problems.map((p) => `FAIL ${p}`).join('\n') + '\n');
      return 1;
    }
    process.stdout.write(`gen-locales: ok (${Object.keys(en).length} ids, en + zh-TW)\n`);
    return 0;
  }
  fs.writeFileSync(path.join(dir, 'locales.ts'), render(en, zh));
  process.stdout.write(`gen-locales: wrote locales.ts (${Object.keys(en).length} ids)\n`);
  return 0;
}

if (require.main === module) process.exit(main(process.argv.slice(2)));
module.exports = { check, render, displayWidth };
